/*
 * Release signing.
 *
 * Credentials are read from `keystore.properties` in the repository root (never committed, see
 * .gitignore) or from environment variables (used by CI):
 *
 *   storeFile / HAPTICSYNC_KEYSTORE_PATH
 *   storePassword / HAPTICSYNC_KEYSTORE_PASSWORD
 *   keyAlias / HAPTICSYNC_KEY_ALIAS
 *   keyPassword / HAPTICSYNC_KEY_PASSWORD
 *
 * When no release key is configured, the release build is signed with the local debug key so
 * that it can still be installed for testing. Such an APK must not be published.
 */
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun signingValue(propertyKey: String, envKey: String): String? =
    keystoreProperties.getProperty(propertyKey)?.takeIf { it.isNotBlank() }
        ?: System.getenv(envKey)?.takeIf { it.isNotBlank() }

val releaseStorePath = signingValue("storeFile", "HAPTICSYNC_KEYSTORE_PATH")
val hasReleaseKey = releaseStorePath != null && rootProject.file(releaseStorePath).exists()

